  <h2 class="text-2xl font-extrabold">Questions fréquentes</h2>
  <div class="prose prose-slate mt-4 max-w-none font-serif text-base leading-relaxed text-slate-700 prose-headings:font-sans prose-headings:font-extrabold prose-a:text-brand-600">
    <h3>Ce score est-il officiel ?</h3>
    <p>
      Non. Ce simulateur donne une estimation basée sur la grille de pondération publique du PSTQ publiée
      par le ministère de l’Immigration, de la Francisation et de l’Intégration (arrêté ministériel du
      20 juin 2025). Seul le pointage calculé dans votre déclaration d’intérêt Arrima officielle fait foi.
    </p>
    <h3>Pourquoi l’anglais n’est-il pas noté ?</h3>
    <p>
      À la différence du SCG fédéral, le PSTQ n’attribue actuellement aucun point à la connaissance de
      l’anglais — seul le français compte, et c’est le facteur le plus lourdement pondéré de la grille.
    </p>
    <h3>Qu’est-ce que la CMM ?</h3>
    <p>
      La Communauté métropolitaine de Montréal (CMM) regroupe Montréal et son agglomération. Plusieurs
      critères de la grille valorisent une installation, un emploi ou des études à l’extérieur de ce
      territoire, pour favoriser la régionalisation de l’immigration.
    </p>
    <h3>Le score change-t-il souvent ?</h3>
    <p>
      Le Québec ajuste sa grille par arrêté ministériel de façon plus fréquente que le fédéral — cette page
      est mise à jour en fonction des changements officiels connus.
    </p>
