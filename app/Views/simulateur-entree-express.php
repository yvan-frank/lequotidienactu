    <h3>Ce score est-il officiel ?</h3>
    <p>
      Non. Ce simulateur donne une estimation basée sur la grille publique du SCG publiée par IRCC. Seul le
      score calculé dans votre profil Entrée express officiel fait foi.
    </p>
    <h3>Qu’est-ce que le NCLC ?</h3>
    <p>
      Les Niveaux de compétence linguistique canadiens (NCLC) traduisent vos résultats aux tests de langue
      reconnus (IELTS, TEF Canada, TCF Canada, CELPIP…) en un barème commun utilisé pour le calcul du SCG.
    </p>
    <h3>Le score change-t-il souvent ?</h3>
    <p>
      IRCC ajuste occasionnellement certains paramètres de la grille (par exemple, les points pour une
      offre d’emploi arrangée ne sont plus attribués depuis mars 2025). Cette page est mise à jour en
      fonction des changements officiels connus.
    </p>
